/**
 * AI Feature Generation (MVP Stub)
 * Mock AI code generation for proof-of-concept
 */

import { Elysia, t } from 'elysia';
import { Database } from 'bun:sqlite';
import type { JWTPayload, AIGenerationRequest, AIGenerationResponse } from '@bree-ai/flysaas-types';
import { authMiddleware } from '../middleware/auth';

const DB_PATH = process.env.DB_PATH || './data/client.db';
const db = new Database(DB_PATH);

export const aiRoutes = new Elysia({ prefix: '/api/ai' })
  .use(authMiddleware)

  // Generate AI feature (MVP stub)
  .post('/generate', ({ body, session }) => {
    const token = session as JWTPayload;
    const orgId = token.org_slug;
    const { prompt } = body as AIGenerationRequest;

    // MVP stub: Generate mock code based on prompt
    const code = generateMockCode(prompt);
    const featureId = crypto.randomUUID();

    // Save to database
    db.query(`
      INSERT INTO features (id, org_id, name, code, enabled)
      VALUES (?, ?, ?, ?, 1)
    `).run(featureId, orgId, prompt, code);

    const response: AIGenerationResponse = {
      feature_id: featureId,
      code,
      status: 'deployed'
    };

    return response;
  }, {
    requireAuth: true,
    body: t.Object({
      prompt: t.String(),
      context: t.Optional(t.Any())
    })
  })

  // List generated features
  .get('/features', ({ session }) => {
    const token = session as JWTPayload;
    const orgId = token.org_slug;

    const features = db.query(`
      SELECT id, org_id, name, description, enabled, created_at, updated_at
      FROM features
      WHERE org_id = ?
      ORDER BY created_at DESC
    `).all(orgId);

    return { features };
  }, { requireAuth: true })

  // Get feature code
  .get('/features/:id', ({ params, session, error }) => {
    const token = session as JWTPayload;
    const orgId = token.org_slug;

    const feature = db.query(`
      SELECT id, org_id, name, description, code, enabled, created_at, updated_at
      FROM features
      WHERE id = ? AND org_id = ?
    `).get(params.id, orgId);

    if (!feature) {
      return error(404, { error: 'Feature not found' });
    }

    return { feature };
  }, { requireAuth: true })

  // Toggle feature enabled status
  .patch('/features/:id', ({ params, body, session, error }) => {
    const token = session as JWTPayload;
    const orgId = token.org_slug;

    const result = db.query(`
      UPDATE features
      SET enabled = ?
      WHERE id = ? AND org_id = ?
    `).run(body.enabled ? 1 : 0, params.id, orgId);

    if (result.changes === 0) {
      return error(404, { error: 'Feature not found' });
    }

    const feature = db.query(`
      SELECT id, org_id, name, description, code, enabled, created_at, updated_at
      FROM features
      WHERE id = ?
    `).get(params.id);

    return { feature };
  }, {
    requireAuth: true,
    body: t.Object({
      enabled: t.Boolean()
    })
  });

